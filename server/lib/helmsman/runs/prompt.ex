defmodule Helmsman.Runs.Prompt do
  @moduledoc """
  The prompt of a run (designs/13 §6, `add-run-lifecycle` decision 10), in
  English, generated by the server.

  The full prompt: the agent's instructions and a separator (both left out
  when the instructions are empty), who the agent is and what it may
  change, the task, why it was started (one line per trigger; a manual
  trigger's instructions follow it, each line quoted with `> `), the
  working directory and, with a task, a request to read it with
  `get_task`. A resumed session gets only why it was started and that
  last line. The task's description, history and feedback are never in
  the prompt, nor is any token.

  With a repository (`add-daemon-git-workspace` decision 3) the working
  directory is a worktree of the task branch: commit, but do not push,
  open pull requests or switch branches; what Helmsman merged before the
  run (rescue branches, the base branch when reopened for a merge
  conflict) and to resolve conflicts first. A resumed session gets those
  lines too, after why it was started.
  """

  alias Helmsman.Actors.Actor
  alias Helmsman.Agents.AgentProfile
  alias Helmsman.Runs.{GitRepo, Run, Spec}
  alias Helmsman.Tasks.Task
  alias Helmsman.Workspaces.Workspace

  @type ctx :: %{
          required(:agent) => Actor.t(),
          required(:profile) => AgentProfile.t(),
          required(:workspace) => Workspace.t(),
          required(:task) => Task.t() | nil,
          required(:names) => %{pos_integer() => String.t()},
          required(:retried) => %{pos_integer() => atom() | nil},
          required(:resume?) => boolean(),
          optional(:repo) => GitRepo.t() | nil
        }

  @doc """
  The prompt of `run`. `ctx`: the agent, its profile, the workspace, the
  task (nil: none), `names` (actor ID → name, for the triggers), `retried`
  (run ID → failure reason, for retry markers), `resume?` and `repo`
  (nil or absent: none).
  """
  @spec build(Run.t(), ctx()) :: String.t()
  def build(%Run{} = run, %{resume?: true, task: %Task{}} = ctx) do
    Enum.join([why(run, ctx)] ++ repo_lines(run, ctx[:repo]) ++ [get_task(ctx.task)], "\n")
  end

  def build(%Run{} = run, ctx) do
    body =
      Enum.join(
        [
          identity(ctx),
          "",
          this_run(ctx.task),
          why(run, ctx)
        ] ++
          working_directory(run, ctx.task, ctx[:repo]) ++
          if(ctx.task, do: [get_task(ctx.task)], else: []),
        "\n"
      )

    case String.trim(ctx.profile.instructions || "") do
      "" -> body
      _ -> ctx.profile.instructions <> "\n\n---\n" <> body
    end
  end

  defp identity(ctx) do
    scope_line =
      case ctx.task do
        %Task{ident: ident} -> "You may only change #{ident}."
        nil -> "You may read the workspace but you cannot change any task in this run."
      end

    Enum.join(
      [
        "You are the agent \"#{ctx.agent.name}\" in the Helmsman workspace " <>
          "\"#{ctx.workspace.slug}\". The Helmsman MCP server (named helmsman) is already " <>
          "configured and your identity is fixed; do not call identify.",
        "Follow the collaboration rules in the MCP resource helmsman://workflow.",
        scope_line
      ],
      "\n"
    )
  end

  defp this_run(nil), do: "This run has no task."

  defp this_run(%Task{ident: ident, title: title}),
    do: "This run: task #{ident} (project #{project_key(ident)}): #{title}"

  defp why(run, ctx) do
    lines = Enum.map(run.triggers, &trigger_line(&1, run, ctx))
    Enum.join(["Why you were started:" | lines], "\n")
  end

  defp trigger_line(%{"kind" => "assign"} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} assigned #{ctx.task && ctx.task.ident} to you."

  defp trigger_line(%{"kind" => "manual"} = trigger, _run, ctx) do
    line = "- #{by(trigger, ctx)} started you manually."

    case trigger["instructions"] do
      text when is_binary(text) and text != "" ->
        quoted = text |> String.split(~r/\r?\n/) |> Enum.map_join("\n", &("> " <> &1))
        Enum.join([line, "Instructions from #{by(trigger, ctx)}:", quoted], "\n")

      _none ->
        line
    end
  end

  defp trigger_line(%{"kind" => "retry", "auto" => true} = trigger, run, ctx) do
    id = trigger["retry_of"]
    reason = Map.get(ctx.retried, id)

    "- This is retry #{run.attempt} after run #{id} failed: #{reason || "unknown"}."
  end

  defp trigger_line(%{"kind" => "retry"} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} retried run #{trigger["retry_of"]}."

  defp trigger_line(%{"kind" => kind} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} started you (#{kind})."

  defp by(trigger, ctx), do: Map.get(ctx.names, trigger["by_actor_id"]) || "Someone"

  defp working_directory(_run, nil, _repo),
    do: ["Working directory: an empty scratch directory for this run only."]

  defp working_directory(_run, %Task{ident: ident}, nil),
    do: [
      "Working directory: an empty scratch directory that is kept for later runs on " <>
        "#{ident}. This project has no repository."
    ]

  defp working_directory(run, %Task{}, repo) do
    %{owner: owner, name: name} = repo.repository

    [
      "Working directory: a git worktree of #{owner}/#{name} on branch #{repo.branch} " <>
        "(based on #{repo.base_branch}). Commit your changes, but do not push, open pull " <>
        "requests, or switch branches; Helmsman does that."
      | repo_lines(run, repo)
    ]
  end

  defp repo_lines(_run, nil), do: []

  defp repo_lines(run, repo) do
    merged =
      repo.rescue_branches ++
        if merge_conflict?(run), do: ["origin/#{repo.base_branch}"], else: []

    merged_line =
      if merged == [],
        do: [],
        else: ["Before this run Helmsman merged #{Enum.join(merged, ", ")} into #{repo.branch}."]

    merged_line ++
      [
        "If `git status` shows unmerged paths, resolve the conflicts and commit them " <>
          "before anything else."
      ]
  end

  defp merge_conflict?(run),
    do: match?(%{kind: "reopen", reason: "merge_conflict"}, Spec.main_trigger(run.triggers))

  defp get_task(%Task{ident: ident}),
    do:
      "Before you start, call get_task(\"#{ident}\") to read the full requirements, " <>
        "history and feedback."

  # Keys never contain "-".
  defp project_key(ident), do: ident |> String.split("-", parts: 2) |> hd()
end
