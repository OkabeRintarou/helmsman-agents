defmodule Helmsman.Runs.Prompt do
  @moduledoc """
  The prompt of a run (designs/13 §6, `add-run-lifecycle` decision 10), in
  English, generated by the server.

  The full prompt: the agent's instructions and a separator (both left out
  when the instructions are empty), who the agent is and what it may
  change, the task, why it was started (one line per trigger; a manual
  trigger's instructions follow it, each line quoted with `> `), the
  working directory and, with a task, a request to read it with
  `get_task`. A resumed session gets only why it was started and that
  last line. The task's description, history and feedback are never in
  the prompt, nor is any token.

  With a repository (`add-daemon-git-workspace` decision 3) the working
  directory is a worktree of the task branch: commit, but do not push,
  open pull requests or switch branches; what Helmsman merged before the
  run (rescue branches, the base branch when reopened for a merge
  conflict) and to resolve conflicts first. A resumed session gets those
  lines too, after why it was started.

  A run as a squad leader (`add-squads` decision 7) gets the squad's
  section after the agent's instructions and before the separator: the
  squad, its instructions (left out of a resumed session), its members and
  how to lead them. Its assignment and mention lines name the squad. The
  prompt of any other run is unchanged.

  A run-only autopilot run (`add-autopilots` decision 11, `autopilot` in
  the context) has no task: after who it is, which autopilot started it
  and how, the frozen instructions, a manual note, a webhook payload (at
  most 32 KB, marked as untrusted data), its temporary working
  directory, what it may do and that its last message is the result.
  """

  alias Helmsman.Actors.Actor
  alias Helmsman.AgentDesigns.Prompt, as: DesignPrompt
  alias Helmsman.Agents.AgentProfile
  alias Helmsman.Autopilots.{Content, Record}
  alias Helmsman.Feedback.Replies
  alias Helmsman.Runs.{GitRepo, LocalRepo, Run, Spec}
  alias Helmsman.Squads
  alias Helmsman.Tasks.Task
  alias Helmsman.Workspaces.Workspace

  @type ctx :: %{
          required(:agent) => Actor.t(),
          required(:profile) => AgentProfile.t(),
          required(:workspace) => Workspace.t(),
          required(:task) => Task.t() | nil,
          required(:names) => %{pos_integer() => String.t()},
          required(:retried) => %{pos_integer() => atom() | nil},
          required(:resume?) => boolean(),
          optional(:repo) => GitRepo.t() | LocalRepo.t() | nil,
          optional(:feedback) => %{
            pos_integer() => %{
              required(:id) => String.t(),
              required(:content) => String.t(),
              optional(:target) => map() | nil
            }
          },
          optional(:squad) => Squads.loaded() | nil,
          optional(:autopilot) => %{record: Record.t(), note_by: String.t() | nil} | nil,
          optional(:delegations) => %{
            summaries: %{pos_integer() => String.t() | nil},
            squads: %{pos_integer() => String.t()}
          }
        }

  @max_quote_bytes 8192
  @autopilot_payload_bytes 32_768
  @squad_description_bytes 400
  @role_note_bytes 300
  @member_description_bytes 200

  @doc """
  The prompt of `run`. `ctx`: the agent, its profile, the workspace, the
  task (nil: none), `names` (actor ID → name, for the triggers), `retried`
  (run ID → failure reason, for retry markers), `resume?` and `repo`
  (nil or absent: none) and `feedback` (feedback ID → the current record
  of its revision chain, `%{id: "KEY-N#S", content, target}`, for the quotes of
  `add-continuation-triggers` decision 9).
  """
  @spec build(Run.t(), ctx()) :: String.t()
  def build(%Run{} = run, %{resume?: true, task: %Task{}} = ctx) do
    body = Enum.join([why(run, ctx)] ++ repo_lines(run, ctx[:repo]) ++ [get_task(ctx.task)], "\n")

    case ctx[:squad] do
      nil -> body
      squad -> squad_section(squad, false) <> "\n\n---\n" <> body
    end
  end

  def build(%Run{}, %{autopilot: %{record: %Record{}} = autopilot} = ctx) do
    body = Enum.join([identity(ctx), "", this_run(nil), autopilot_section(autopilot, ctx)], "\n")

    case String.trim(ctx.profile.instructions || "") do
      "" -> body
      _ -> ctx.profile.instructions <> "\n\n---\n" <> body
    end
  end

  def build(%Run{} = run, ctx) do
    body =
      Enum.join(
        [
          identity(ctx),
          "",
          this_run(ctx.task),
          why(run, ctx)
        ] ++
          working_directory(run, ctx.task, ctx[:repo]) ++
          if(ctx.task, do: [get_task(ctx.task)], else: []),
        "\n"
      )

    head =
      case String.trim(ctx.profile.instructions || "") do
        "" -> []
        _ -> [ctx.profile.instructions]
      end

    head = head ++ if(ctx[:squad], do: [squad_section(ctx.squad, true)], else: [])

    case head do
      [] -> body
      _ -> Enum.join(head, "\n\n") <> "\n\n---\n" <> body
    end
  end

  ## The squad section (`add-squads` decision 7)

  @doc """
  The section of a run as the leader of the `t:Helmsman.Squads.loaded/0`
  squad, with its instructions or not (a resumed session). The squad's
  description, the members' role notes and agent descriptions are bounded
  summaries (#{@squad_description_bytes}, #{@role_note_bytes} and
  #{@member_description_bytes} bytes, `Helmsman.AgentDesigns.Prompt.prefix/2`);
  the instructions are whole.
  """
  @spec squad_section(Squads.loaded(), boolean()) :: String.t()
  def squad_section(loaded, instructions?) do
    name = loaded.actor.name
    {description, _cut?} = summary(loaded.squad.description, @squad_description_bytes)
    intro = String.trim("In this run you lead the squad #{name}. #{description}")

    instructions =
      case loaded.squad.instructions do
        text when instructions? and is_binary(text) and text != "" ->
          ["", "Squad instructions:", text]

        _none ->
          []
      end

    members =
      case loaded.members do
        [] -> ["- (none yet)"]
        members -> Enum.map(members, &member_line/1)
      end

    Enum.join(
      ["## Squad #{name}", intro] ++
        instructions ++ ["", "Members:"] ++ members ++ ["", "How to lead:"] ++ how_to_lead(),
      "\n"
    )
  end

  defp member_line(%{actor: %Actor{kind: :agent} = actor, profile: profile, member: member}) do
    profile = profile || %AgentProfile{}
    {note, note_cut?} = summary(member.role_note, @role_note_bytes)
    {desc, desc_cut?} = summary(profile.description, @member_description_bytes)
    member_text(agent_head(actor, profile), note, desc, note_cut? or desc_cut?)
  end

  defp member_line(%{actor: actor, member: member}) do
    {note, cut?} = summary(member.role_note, @role_note_bytes)
    member_text("- #{actor.name} (person)", note, "", cut?)
  end

  defp agent_head(actor, profile) do
    disabled = if actor.disabled_at, do: "; disabled, cannot be delegated now", else: ""

    "- #{actor.name} (agent; #{profile.provider}, model #{profile.model || "CLI default"}, " <>
      "effort #{profile.effort || "CLI default"}#{disabled})"
  end

  defp member_text(head, note, desc, cut?) do
    text =
      case {note, desc} do
        {"", ""} -> head
        {note, ""} -> "#{head}: #{note}"
        {"", desc} -> "#{head}: #{desc}"
        {note, desc} -> "#{head}: #{note} — #{desc}"
      end

    if cut?, do: text <> " (truncated; list_agents has the full text)", else: text
  end

  # On one line, at most `max` bytes (cut between code points, `…` added).
  defp summary(nil, _max), do: {"", false}

  defp summary(text, max) do
    text = text |> String.replace(~r/\s*[\r\n]+\s*/u, " ") |> String.trim()

    case DesignPrompt.prefix(text, max) do
      {kept, true} -> {kept <> "…", true}
      {kept, false} -> {kept, false}
    end
  end

  defp how_to_lead do
    [
      "- Hand work on this task to a member agent with delegate(task_id, to, instructions). " <>
        "The member works on the same task, branch and pull request, but only after this run " <>
        "ends: after delegating, finish this run without waiting. Helmsman wakes you with the " <>
        "member's final output when its run ends.",
      "- Parts that can be delivered on their own can become subtasks: create_task with a " <>
        "member as assignee, grouped with epic and ordered with depends_on (the IDs of the " <>
        "tasks one waits for). Create them all in this run: a subtask whose prerequisites are " <>
        "not done yet starts by itself when they are. Do not create one with start=false to " <>
        "start it later: a run can only change its own task, so you could not. You are woken " <>
        "when they are done or rejected, or when the assignee asks a question.",
      "- Prefer delegate for code changes: they land in one pull request that is verified once.",
      "- You cannot create agents or change the squad. If a role is missing, say so in a " <>
        "question on the task; a person can add one.",
      "- People in the squad cannot be delegated runs; write a question when you need their " <>
        "decision.",
      "- When the whole goal is met, move the task to done with commits and tests; its " <>
        "requester verifies it. Do not verify it yourself or have a member verify it."
    ]
  end

  defp identity(ctx) do
    scope_line =
      case {ctx.task, ctx[:autopilot]} do
        {%Task{ident: ident}, _} ->
          "You may only change #{ident}."

        {nil, %{record: %Record{config: %{"create_tasks" => true}}}} ->
          "You may read the workspace and create tasks, but you cannot change any existing " <>
            "task in this run."

        {nil, _} ->
          "You may read the workspace but you cannot change any task in this run."
      end

    Enum.join(
      [
        "You are the agent \"#{ctx.agent.name}\" in the Helmsman workspace " <>
          "\"#{ctx.workspace.slug}\". The Helmsman MCP server (named helmsman) is already " <>
          "configured and your identity is fixed; do not call identify.",
        "Follow the collaboration rules in the MCP resource helmsman://workflow.",
        scope_line
      ],
      "\n"
    )
  end

  defp this_run(nil), do: "This run has no task."

  defp this_run(%Task{ident: ident, title: title}),
    do: "This run: task #{ident} (project #{project_key(ident)}): #{title}"

  ## A run-only autopilot run (`add-autopilots` decision 11)

  defp autopilot_section(%{record: record} = autopilot, ctx) do
    config = record.config

    [
      "Why you were started:",
      "- Autopilot #{config["name"]} started you (#{autopilot_source(record, autopilot)}).",
      "",
      "Instructions:",
      config["instructions"]
    ]
    |> Kernel.++(note_lines(record, autopilot))
    |> Kernel.++(payload_lines(record))
    |> Kernel.++(["", autopilot_directory(ctx[:repo])])
    |> Kernel.++([
      "Your last message is recorded as the result of this autopilot run; end with a " <>
        "concise summary."
    ])
    |> Enum.join("\n")
  end

  defp autopilot_source(%Record{source: :schedule} = record, _autopilot),
    do:
      "scheduled for " <>
        Content.local_time(record.scheduled_for || record.inserted_at, record.config["timezone"])

  defp autopilot_source(%Record{source: :manual}, autopilot),
    do: "run now by #{autopilot.note_by || "someone"}"

  defp autopilot_source(%Record{source: :webhook} = record, _autopilot),
    do: "webhook delivery #{record.delivery_id || "without an ID"}"

  defp note_lines(%Record{note: note}, _autopilot) when note in [nil, ""], do: []

  defp note_lines(%Record{note: note}, autopilot),
    do: ["", String.trim_leading(Content.note_block(note, autopilot.note_by || "someone"))]

  defp payload_lines(%Record{payload: nil}), do: []

  defp payload_lines(%Record{payload: payload}),
    do: [
      "",
      String.trim_leading(
        Content.payload_block(payload, @autopilot_payload_bytes, "at most 32 KB")
      )
    ]

  defp autopilot_directory(%{base_branch: base}),
    do:
      "Working directory: a temporary checkout of #{base}; nothing you change is kept or " <>
        "pushed."

  defp autopilot_directory(_none),
    do: "Working directory: a temporary directory for this run only; nothing in it is kept."

  defp why(run, ctx) do
    lines =
      run.triggers
      |> Enum.uniq_by(&line_key/1)
      |> Enum.map(&trigger_line(&1, run, ctx))
      |> Enum.reject(&is_nil/1)

    Enum.join(["Why you were started:" | lines], "\n")
  end

  # Several sources of one member's run wake the leader once in the prompt.
  defp line_key(%{"kind" => "delegate_done", "delegated_run_id" => id}), do: {:delegate_done, id}
  defp line_key(trigger), do: {:trigger, make_ref(), trigger}

  defp trigger_line(%{"kind" => "assign"} = trigger, _run, %{squad: %{actor: squad}} = ctx),
    do: "- #{by(trigger, ctx)} assigned #{ident(ctx)} to your squad #{squad.name}."

  defp trigger_line(%{"kind" => "assign"} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} assigned #{ctx.task && ctx.task.ident} to you."

  defp trigger_line(%{"kind" => "manual"} = trigger, _run, ctx) do
    line = "- #{by(trigger, ctx)} started you manually."

    case trigger["instructions"] do
      text when is_binary(text) and text != "" ->
        quoted = text |> String.split(~r/\r?\n/) |> Enum.map_join("\n", &("> " <> &1))
        Enum.join([line, "Instructions from #{by(trigger, ctx)}:", quoted], "\n")

      _none ->
        line
    end
  end

  defp trigger_line(%{"kind" => "retry", "auto" => true} = trigger, run, ctx) do
    id = trigger["retry_of"]
    reason = Map.get(ctx.retried, id)

    "- This is retry #{run.attempt} after run #{id} failed: #{reason || "unknown"}."
  end

  defp trigger_line(%{"kind" => "retry"} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} retried run #{trigger["retry_of"]}."

  defp trigger_line(%{"kind" => "reopen", "reason" => "ci_failed"} = trigger, _run, ctx) do
    ident = ident(ctx)

    quoted(
      "- CI failed on the pull request for #{ident}, so Helmsman reopened it. Details in",
      trigger["feedback_id"],
      ctx
    )
  end

  defp trigger_line(%{"kind" => "reopen", "reason" => "merge_conflict"} = trigger, _run, ctx) do
    ident = ident(ctx)

    quoted(
      "- The pull request for #{ident} has merge conflicts with its base branch, so " <>
        "Helmsman reopened it. Details in",
      trigger["feedback_id"],
      ctx
    )
  end

  defp trigger_line(%{"kind" => "reopen"} = trigger, _run, ctx) do
    line =
      case trigger["from"] do
        "verified" -> "- #{by(trigger, ctx)} reopened #{ident(ctx)} after it was verified."
        _done -> "- #{by(trigger, ctx)} sent #{ident(ctx)} back to in progress."
      end

    join([line | quote_lines("Review", trigger["feedback_id"], ctx)])
  end

  defp trigger_line(%{"kind" => "resubmit"} = trigger, _run, ctx) do
    "- #{by(trigger, ctx)} changed the requirements of #{ident(ctx)} and resubmitted it. " <>
      "Read them again with get_task before you continue."
  end

  defp trigger_line(%{"kind" => "answer"} = trigger, _run, ctx) do
    question = feedback_id(trigger["question_id"], ctx) || "#{ident(ctx)}#?"

    quoted(
      "- #{by(trigger, ctx)} answered your question #{question} in",
      trigger["feedback_id"],
      ctx
    )
  end

  defp trigger_line(%{"kind" => "requested", "event" => "done"}, _run, ctx) do
    "- #{ident(ctx)}, which you created, is done. Review the work, then verify it " <>
      "(transition_task to \"verified\") or send it back (transition_task to " <>
      "\"in_progress\") with a review."
  end

  defp trigger_line(%{"kind" => "requested", "event" => "rejected"} = trigger, _run, ctx) do
    join(
      ["- #{by(trigger, ctx)} rejected #{ident(ctx)}, which you created."] ++
        quote_lines("Reason", trigger["feedback_id"], ctx) ++
        [
          "Revise the requirements with update_task and resubmit it (transition_task to " <>
            "\"new\"), or leave it rejected."
        ]
    )
  end

  defp trigger_line(%{"kind" => "requested"} = trigger, _run, ctx) do
    join([
      quoted(
        "- #{by(trigger, ctx)} asked a question on #{ident(ctx)}, which you created, in",
        trigger["feedback_id"],
        ctx
      ),
      "Answer it with add_feedback (kind \"answer\")."
    ])
  end

  # `add-run-steering` decision 13.
  defp trigger_line(%{"kind" => "steer"} = trigger, _run, ctx) do
    lead = "- #{by(trigger, ctx)} wrote"

    tail =
      "while your run #{trigger["steer_run_id"]} was in progress; that run did not " <>
        "finish with it. Act on it now unless you already have:"

    case Map.get(ctx[:feedback] || %{}, trigger["feedback_id"]) do
      %{id: id, content: content} = entry ->
        join(["#{lead} #{id}#{reply_suffix(entry)} #{tail}", blockquote(content)])

      nil ->
        "#{lead} a feedback record #{tail}"
    end
  end

  defp trigger_line(%{"kind" => "mention"} = trigger, _run, ctx) do
    whom =
      case ctx[:squad] do
        %{actor: squad} -> "your squad #{squad.name}"
        nil -> "you"
      end

    join([
      quoted("- #{by(trigger, ctx)} mentioned #{whom} in", trigger["feedback_id"], ctx),
      "Reply with add_feedback. You were asked to reply, not to take over #{ident(ctx)}."
    ])
  end

  # `add-squads` decision 8: a member's run.
  defp trigger_line(%{"kind" => "delegated"} = trigger, _run, ctx) do
    squad = get_in(ctx, [:delegations, :squads, trigger["squad_id"]]) || "your squad"

    join([
      "- #{by(trigger, ctx)}, leading the squad #{squad}, delegated #{ident(ctx)} to you:",
      blockquote(trigger["instructions"] || ""),
      "Do this in this run and end it with a short summary of what you did: the leader " <>
        "reads it. Do not move #{ident(ctx)} to done unless asked to, and do not verify it."
    ])
  end

  # `add-squads` decision 9: a leader woken by its member's run.
  defp trigger_line(%{"kind" => "delegate_done"} = trigger, _run, ctx) do
    id = trigger["delegated_run_id"]

    status =
      case {trigger["status"], trigger["failure_reason"]} do
        {"failed", reason} when is_binary(reason) -> "failed (#{reason})"
        {status, _reason} -> status
      end

    output =
      case get_in(ctx, [:delegations, :summaries, id]) do
        text when is_binary(text) and text != "" -> blockquote(text)
        _none -> "(no output)"
      end

    join([
      "- The run of #{trigger["member"]} (run #{id}) that you delegated #{ident(ctx)} to " <>
        "has ended: #{status}.",
      "Its final output:",
      output
    ])
  end

  # `add-dependency-dispatch` decision 11; nothing without prerequisites.
  defp trigger_line(%{"kind" => "unblocked", "prerequisites" => [_ | _] = idents}, _run, ctx),
    do:
      "- The tasks #{ident(ctx)} depends on are finished (their changes, if any, " <>
        "are merged into the base branch): #{Enum.join(idents, ", ")}. You can start."

  defp trigger_line(%{"kind" => "unblocked"}, _run, _ctx), do: nil

  defp trigger_line(%{"kind" => kind} = trigger, _run, ctx),
    do: "- #{by(trigger, ctx)} started you (#{kind})."

  defp ident(ctx), do: ctx.task && ctx.task.ident

  defp feedback_id(id, ctx) do
    case Map.get(ctx[:feedback] || %{}, id) do
      %{id: ident} -> ident
      nil -> nil
    end
  end

  # `<text> <IDENT>#<n>:` and the quote (a record is never deleted).
  defp reply_suffix(entry) do
    case Replies.label(entry) do
      "" -> ""
      label -> " (" <> label <> ")"
    end
  end

  defp quoted(text, feedback_id, ctx) do
    case Map.get(ctx[:feedback] || %{}, feedback_id) do
      %{id: id, content: content} = entry ->
        join(["#{text} #{id}#{reply_suffix(entry)}:", blockquote(content)])

      nil ->
        text <> " a feedback record."
    end
  end

  # `<label> <IDENT>#<n>:` and the quote, or nothing.
  defp quote_lines(label, feedback_id, ctx) do
    case Map.get(ctx[:feedback] || %{}, feedback_id) do
      %{id: id, content: content} = entry ->
        ["#{label} #{id}#{reply_suffix(entry)}:", blockquote(content)]

      nil ->
        []
    end
  end

  @doc """
  `content` quoted (`add-continuation-triggers` decision 9): each line
  after `> `; over #{@max_quote_bytes} bytes it is cut and a last quoted
  line says to read the full text with `get_task`.
  """
  @spec blockquote(String.t()) :: String.t()
  def blockquote(content) do
    {text, truncated?} = truncate(content)
    lines = text |> String.split(~r/\r?\n/) |> Enum.map_join("\n", &("> " <> &1))
    if truncated?, do: lines <> "\n> …(truncated; read the full text with get_task)", else: lines
  end

  defp truncate(text) when byte_size(text) <= @max_quote_bytes, do: {text, false}

  defp truncate(text) do
    cut = binary_part(text, 0, @max_quote_bytes)
    {valid_prefix(cut), true}
  end

  # Drops a UTF-8 sequence cut in two at the end.
  defp valid_prefix(binary) do
    if String.valid?(binary),
      do: binary,
      else: valid_prefix(binary_part(binary, 0, byte_size(binary) - 1))
  end

  defp join(lines), do: Enum.join(lines, "\n")

  defp by(trigger, ctx), do: Map.get(ctx.names, trigger["by_actor_id"]) || "Someone"

  defp working_directory(_run, nil, _repo),
    do: ["Working directory: an empty scratch directory for this run only."]

  defp working_directory(_run, %Task{ident: ident}, nil),
    do: [
      "Working directory: an empty scratch directory that is kept for later runs on " <>
        "#{ident}. This project has no repository."
    ]

  # `add-local-repositories` decision 7: the repository's name and
  # machine, never its path.
  defp working_directory(run, %Task{}, %{kind: :local} = repo) do
    [
      "Working directory: a git worktree of the local repository " <>
        "#{repo.local_repository.name} on #{repo.daemon_name}, on branch #{repo.branch} " <>
        "(based on #{repo.base_branch}). Commit your changes, but do not push, switch " <>
        "branches, or modify any other checkout of this repository; Helmsman delivers the " <>
        "branch to the repository for local review."
      | repo_lines(run, repo)
    ]
  end

  defp working_directory(run, %Task{}, repo) do
    %{owner: owner, name: name} = repo.repository

    [
      "Working directory: a git worktree of #{owner}/#{name} on branch #{repo.branch} " <>
        "(based on #{repo.base_branch}). Commit your changes, but do not push, open pull " <>
        "requests, or switch branches; Helmsman does that."
      | repo_lines(run, repo)
    ]
  end

  defp repo_lines(_run, nil), do: []

  defp repo_lines(run, repo) do
    merged =
      repo.rescue_branches ++
        if merge_conflict?(run), do: ["origin/#{repo.base_branch}"], else: []

    merged_line =
      if merged == [],
        do: [],
        else: ["Before this run Helmsman merged #{Enum.join(merged, ", ")} into #{repo.branch}."]

    merged_line ++
      [
        "If `git status` shows unmerged paths, resolve the conflicts and commit them " <>
          "before anything else."
      ]
  end

  defp merge_conflict?(run),
    do: match?(%{kind: "reopen", reason: "merge_conflict"}, Spec.main_trigger(run.triggers))

  defp get_task(%Task{ident: ident}),
    do:
      "Before you start, call get_task(\"#{ident}\") to read the full requirements, " <>
        "history and feedback."

  # Keys never contain "-".
  defp project_key(ident), do: ident |> String.split("-", parts: 2) |> hd()
end
